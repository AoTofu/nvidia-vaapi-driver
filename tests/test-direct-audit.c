    NVContext ctx = {.renderTarget = &surface};
    NVContext other = {.renderTarget = &surface};
    CUVIDPICPARAMS params = {0};
    pthread_mutex_init(&surface.mutex, NULL);
    parseExtraInfo(&ctx, frame, sizeof(frame), &params);
    assert(!ctx.inputValidationFailed);
    VP9Context *vp9 = ctx.codecData;
    GstVp9Parser *parser = vp9->parser;
    uint8_t invalidHeader[] = {0, 0}; // Invalid VP9 frame marker.
    parseExtraInfo(&ctx, invalidHeader, sizeof(invalidHeader), &params);
