static void testWorkerFailures(void) {
    CudaFunctions cuda = {.cuMemcpy2DAsync = mockCopy, .cuStreamSynchronize = mockSync,
        .cuEventRecord = mockEvent, .cuCtxPushCurrent = mockPush, .cuCtxPopCurrent = mockPop,
        .cuStreamCreate = mockCreateStream, .cuEventCreate = mockCreateEvent,
        .cuStreamDestroy = mockDestroyStream, .cuEventDestroy = mockDestroyEvent};
    CuvidFunctions cuvid = {.cuvidMapVideoFrame = mockMap,
        .cuvidUnmapVideoFrame = mockUnmap, .cuvidDestroyDecoder = mockDestroyDecoder};
    cu = &cuda;
    cv = &cuvid;
    for (unsigned scenario = 0; scenario < 5; scenario++) {
        copies = syncs = events = unmaps = decoderDestroys = 0;
        copyFailure = scenario == 1 ? 2 : 0;
        eventFailure = scenario == 2;
        syncFailure = scenario == 3;
        pushFailure = scenario == 4;
        NVDriver drv = {.cu = &cuda, .backend = &DIRECT_BACKEND};
        BackingImage img = {.format = NV_FORMAT_NV12};
        assert(initBackingImageSync(&img));
        NVSurface surface = {.width = 128, .height = 128, .backingImage = &img,
            .resolving = 1, .submittedGeneration = 1};
        pthread_mutex_init(&surface.mutex, NULL);
        pthread_cond_init(&surface.cond, NULL);
        workerSurface = &surface;
        NVContext ctx = {.drv = &drv, .decoder = (CUvideodecoder)1};
        assert(resolveQueueInit(&ctx.resolveQueue));
        ResolveJob *job = calloc(1, sizeof(*job));
        assert(job != NULL);
        job->surface = &surface;
        job->decoder = ctx.decoder;
        job->generation = 1;
        assert(resolveQueuePush(&ctx.resolveQueue, job));
        resolveQueueShutdown(&ctx.resolveQueue);
        resolveSurfaces(&ctx);
        assert(!surface.resolving && !img.resolving);
        assert(surface.decodeFailed == (scenario != 0));
        assert(unmaps == (scenario < 3 ? 1 : 0));
        assert(decoderDestroys == (scenario < 3 ? 1 : 0));
        assert(atomic_load(&drv.cudaWorkUnsafe) == (scenario == 3));
        resolveQueueDestroy(&ctx.resolveQueue);
        pthread_cond_destroy(&surface.cond);
        pthread_mutex_destroy(&surface.mutex);
        pthread_cond_destroy(&img.cond);
        pthread_mutex_destroy(&img.mutex);
    }
    cu = NULL;
    cv = NULL;
}

