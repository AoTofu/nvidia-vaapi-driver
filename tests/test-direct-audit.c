static void testUuid(void) {
    NVDriverContext ctx = {0};
    uint8_t uuid[16];
    for (rmFailure = 0; rmFailure < 3; rmFailure++) {
        memset(uuid, 0xcc, sizeof(uuid));
        assert(get_device_uuid(&ctx, uuid) == (rmFailure == 0));
        for (unsigned i = 0; i < 16; i++) assert(uuid[i] == (rmFailure == 0 ? 0x5a : 0xcc));
    }
}

