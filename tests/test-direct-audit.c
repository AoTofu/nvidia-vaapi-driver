static void testLayout(void) {
    NVDriverContext ctx = {0};
    NVDriverImage images[3] = {0};
    const NVFormatInfo *fmt = &formatsInfo[NV_FORMAT_NV12];
    uint32_t size = 123;
    assert(!calculate_unified_image_layout(&ctx, images, 65534, 43690, 1, 2, fmt->plane, true, &size));
    assert(size == 0);
    const uint32_t dimensions[][2] = {{1,1}, {63,65}, {128,128}, {256,144}, {1920,1080}, {3840,2160}, {7680,4320}};
    for (unsigned f = NV_FORMAT_NV12; f <= NV_FORMAT_ARGB; f++) {
        fmt = &formatsInfo[f];
        if (fmt->numPlanes == 0) continue;
        for (unsigned d = 0; d < ARRAY_SIZE(dimensions); d++) {
            for (unsigned shared = 0; shared < 2; shared++) {
                assert(calculate_unified_image_layout(&ctx, images, dimensions[d][0], dimensions[d][1],
                    fmt->bppc, fmt->numPlanes, fmt->plane, shared, &size));
                for (unsigned p = 0; p < fmt->numPlanes; p++) {
                    assert((uint64_t) images[p].offset + images[p].memorySize <= size);
                    assert(images[p].pitch >= (uint64_t) images[p].width * fmt->bppc * fmt->plane[p].channelCount);
                    assert(images[p].offset % 65536 == 0);
                }
            }
        }
    }
    fmt = &formatsInfo[NV_FORMAT_NV12];
    assert(!calculate_unified_image_layout(&ctx, images, 0, 1, 1, 2, fmt->plane, true, &size));
    assert(!calculate_unified_image_layout(&ctx, images, UINT32_MAX, UINT32_MAX, 2, 2, fmt->plane, true, &size));
    assert(!alloc_image(&ctx, UINT32_MAX, UINT32_MAX, 4, 16, 0, images));
}

static void closeDescriptor(VADRMPRIMESurfaceDescriptor *desc) {
    for (unsigned i = 0; i < desc->num_objects; i++) close(desc->objects[i].fd);
}

static void testDescriptor(void) {
    NVDriver drv = {0};
    FILE *a = tmpfile(), *b = tmpfile();
    assert(a != NULL && b != NULL);
    BackingImage img = {.format = NV_FORMAT_NV12, .fourcc = VA_FOURCC_NV12,
        .numObjects = 2, .numPlanes = 2, .fds = {fileno(a), fileno(b)},
        .objectSize = {8192, 16384}, .planeObjectIndex = {1, 0},
        .strides = {128, 128}, .mods = {DRM_FORMAT_MOD_LINEAR, DRM_FORMAT_MOD_LINEAR}};
    NVSurface surface = {.width = 128, .height = 128, .backingImage = &img};
    VADRMPRIMESurfaceDescriptor desc;
    assert(direct_fillExportDescriptor(&drv, &surface, &desc));
    assert(desc.num_objects == 2 && desc.layers[0].object_index[0] == 1 && desc.layers[1].object_index[0] == 0);
    assert(desc.objects[0].size == 8192 && desc.objects[1].size == 16384);
    struct stat original, exported;
    assert(fstat(fileno(b), &original) == 0 && fstat(desc.objects[1].fd, &exported) == 0);
    assert(original.st_ino == exported.st_ino && original.st_dev == exported.st_dev);
    assert(fcntl(desc.objects[0].fd, F_GETFD) & FD_CLOEXEC);
    closeDescriptor(&desc);
    img.numObjects = 1;
    img.planeObjectIndex[0] = 0;
    img.objectSize[0] = 24576;
    img.offsets[1] = 16384;
    assert(direct_fillExportDescriptor(&drv, &surface, &desc));
    assert(desc.num_objects == 1 && desc.layers[1].offset[0] == 16384);
    closeDescriptor(&desc);
    const uint32_t rgb[][2] = {
        {VA_FOURCC_ARGB, DRM_FORMAT_BGRA8888}, {VA_FOURCC_XRGB, DRM_FORMAT_BGRX8888},
        {VA_FOURCC_ABGR, DRM_FORMAT_RGBA8888}, {VA_FOURCC_XBGR, DRM_FORMAT_RGBX8888},
        {VA_FOURCC_RGBA, DRM_FORMAT_ABGR8888}, {VA_FOURCC_RGBX, DRM_FORMAT_XBGR8888},
        {VA_FOURCC_BGRA, DRM_FORMAT_ARGB8888}, {VA_FOURCC_BGRX, DRM_FORMAT_XRGB8888}};
    img.format = NV_FORMAT_ARGB;
    img.numPlanes = 1;
    for (unsigned i = 0; i < ARRAY_SIZE(rgb); i++) {
        img.fourcc = rgb[i][0];
        assert(direct_fillExportDescriptor(&drv, &surface, &desc));
        assert(desc.fourcc == rgb[i][0] && desc.layers[0].drm_format == rgb[i][1]);
        closeDescriptor(&desc);
    }
    img.objectSize[0] = UINT64_C(1) << 32;
    assert(!direct_fillExportDescriptor(&drv, &surface, &desc));
    assert(desc.num_objects == 0);
    fclose(a);
    fclose(b);
}

static void testCopyFailures(void) {
    CudaFunctions cuda = {.cuMemcpy2DAsync = mockCopy, .cuStreamSynchronize = mockSync,
        .cuEventRecord = mockEvent, .cuMemsetD8Async = mockMemset};
    NVDriver drv = {.cu = &cuda};
    BackingImage img = {.format = NV_FORMAT_NV12, .width = 4096, .height = 4096};
    NVSurface surface = {.width = 128, .height = 128, .backingImage = &img};
    for (unsigned scenario = 0; scenario < 4; scenario++) {
        copies = syncs = events = 0;
        copyFailure = scenario == 1 ? 1 : scenario == 2 ? 2 : 0;
        syncFailure = scenario == 3;
        atomic_store(&drv.cudaWorkUnsafe, false);
        assert(copyFrameToSurface(&drv, 1, &surface, 128, (CUstream)1) == (scenario == 0));
        assert(syncs == 1 && events == 0);
        assert(atomic_load(&drv.cudaWorkUnsafe) == (scenario == 3));
    }
    pthread_mutex_init(&drv.securityClearMutex, NULL);
    drv.securityClearStream = (CUstream)1;
    drv.securityClearBuffer = 1;
    drv.securityClearBufferSize = 8 * 1024 * 1024;
    copies = syncs = events = 0;
    copyFailure = 2;
    syncFailure = 0;
    atomic_store(&drv.cudaWorkUnsafe, false);
    assert(!clearBackingImageGpu(&drv, &img));
    assert(copies == 2 && syncs == 1 && !atomic_load(&drv.cudaWorkUnsafe));
    copies = syncs = 0;
    syncFailure = 1;
    assert(!clearBackingImage(&drv, &img)); // No CPU fallback after failed drain.
    assert(atomic_load(&drv.cudaWorkUnsafe));
    // A quarantined image must not be freed, even on allocation cleanup.
    destroyBackingImage(&drv, &img);
    pthread_mutex_destroy(&drv.securityClearMutex);
}

