    assert(((VP9Context *)other.codecData)->parser != parser);
    destroyVP9Context(&ctx);
    destroyVP9Context(&other);
    free(ctx.codecData);
    free(other.codecData);
    pthread_mutex_destroy(&surface.mutex);
